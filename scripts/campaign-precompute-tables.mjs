#!/usr/bin/env node
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { generateAllTables } from "../packages/campaign-metastratum/src/tables-generate.mjs";

function arg(name, fallback) {
  const idx = process.argv.indexOf(name);
  if (idx === -1) return fallback;
  return process.argv[idx + 1];
}

const outDir = arg("--out", "campaign/tables/v1");
const bundle = generateAllTables();
mkdirSync(outDir, { recursive: true });
writeFileSync(path.join(outDir, "pacing-tables.json"), `${JSON.stringify(bundle, null, 2)}\n`);
writeFileSync(
  path.join(outDir, "magnitude.json"),
  `${JSON.stringify({ version: bundle.version, rows: bundle.magnitude }, null, 2)}\n`,
);
writeFileSync(
  path.join(outDir, "doomsday-occurrence.json"),
  `${JSON.stringify({ version: bundle.version, rows: bundle.doomsday }, null, 2)}\n`,
);
writeFileSync(
  path.join(outDir, "late-run-adjustment.json"),
  `${JSON.stringify({ version: bundle.version, rows: bundle.lateRun }, null, 2)}\n`,
);
writeFileSync(
  path.join(outDir, "SOURCE-RECEIPT.md"),
  `# Pacing table source receipt

- Formula version: campaign-pacing-tables/v1
- Constants: ${JSON.stringify(bundle.constants)}
- tableHash: \`${bundle.tableHash}\`
- Generated by: \`npm run campaign:precompute-tables\`
- Independent validation: \`npm run validate:campaign-tables\`
`,
);
console.log(JSON.stringify({ ok: true, outDir, tableHash: bundle.tableHash }));
