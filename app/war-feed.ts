const FEED_WINDOW_MS = 24 * 60 * 60 * 1000;

export type WarFeedItem = {
  timestamp: number;
  artifact: (typeof WAR_FEED_ARTIFACTS)[number];
};

export const warFeedForInvocation = (invokedAt: number): WarFeedItem[] => {
  const rotation = Math.floor(invokedAt / (FEED_WINDOW_MS / WAR_FEED_ARTIFACTS.length));
  return WAR_FEED_ARTIFACTS.map((_, index) => ({
    timestamp:
      invokedAt -
      Math.round((index * FEED_WINDOW_MS) / (WAR_FEED_ARTIFACTS.length - 1)),
    artifact:
      WAR_FEED_ARTIFACTS[
        (rotation - index + WAR_FEED_ARTIFACTS.length * 2) %
          WAR_FEED_ARTIFACTS.length
      ],
  }));
};
